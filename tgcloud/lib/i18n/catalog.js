export function catalogName(lang, name) {
  return (lang !== 'en' && CATALOG[lang] && CATALOG[lang][name]) || name;
}

// English catalogue names whose translation contains `needle` (lower-case).
export function catalogSearch(lang, needle) {
  const d = lang !== 'en' && CATALOG[lang];
  if (!d || !needle) return [];
  return Object.keys(d).filter((en) => d[en].toLowerCase().includes(needle));
}
